func SegoeUIRegularAllows(cp uint32) bool {
	if cp > 0xFFFF {
		return false
	}
	u := uint16(cp)
	lo, hi := 0, len(SegoeUIRegularCoverage)
	for lo < hi {
		mid := lo + (hi-lo)/2
		r := SegoeUIRegularCoverage[mid]
		if u < r.First {
			hi = mid
			continue
		}
		if u > r.Last {
			lo = mid + 1
			continue
		}
		return true
	}
	return false
}
